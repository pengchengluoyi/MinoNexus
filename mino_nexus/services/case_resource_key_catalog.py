def _entry(
    *,
    section: str,
    write_category: str,
    write_examples: list[str],
    claim_path: str,
    resource: str,
    config_keys: list[str],
    dsl: str,
    runtime: str,
    key_layer: str = "precondition",
    key_ref: str = "",
    expands_to: list[dict[str, Any]] | None = None,
    kind: str = "",
    block_id: str = "",
    observe: str = "",
    compile_patterns: list[dict[str, Any]] | None = None,
    schemes: list[str] | None = None,
    platforms: list[str] | None = None,
    event_name: str = "",
    slots: list[dict[str, Any]] | None = None,
    param_slots: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    row: dict[str, Any] = {
        "section": section,
        "key_layer": key_layer,
        "write_category": write_category,
        "write_examples": write_examples,
        "claim_path": claim_path,
        "resource": resource,
        "config_keys": config_keys,
        "dsl": dsl,
        "runtime": runtime,
    }
    if key_ref:
        row["key_ref"] = key_ref
    if expands_to:
        row["expands_to"] = list(expands_to)
    if kind:
        row["kind"] = kind
    if block_id:
        row["block_id"] = block_id
    obs = str(observe or "").strip().lower()
    if obs in ("exec", "visual_each_run", "program"):
        row["observe"] = obs
    if compile_patterns:
        row["compile_patterns"] = list(compile_patterns)
    if schemes:
        row["schemes"] = list(schemes)
    if platforms:
        row["platforms"] = list(platforms)
    if event_name:
        row["event_name"] = event_name
    if slots:
        row["slots"] = list(slots)
    if param_slots:
        row["param_slots"] = list(param_slots)
    return row


